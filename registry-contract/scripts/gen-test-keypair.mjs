// One-shot — generate a deterministic ed25519 keypair, sign the canonical
// deactivate-by-controller message for fixed test inputs, print everything
// for embedding in the Rust unit tests.
//
//   node scripts/gen-test-keypair.mjs
//
// Output stays stable across runs because the keypair seed is hard-coded.
// If you change the test message constants below, the printed bytes change
// and the test fixtures must be re-generated.

import nacl from 'tweetnacl';
import bs58 from 'bs58';

const WORKER_DID = 'did:key:z6MkController1';
const NONCE = 'nonce-1';
const NONCE_OTHER = 'nonce-2';
const DOMAIN = Buffer.from('delibera.deactivate-worker.v1\x00');

// Deterministic 32-byte seed -> ed25519 keypair (use any constant)
const seed = Buffer.from('delibera-test-controller-seed-42'.padEnd(32, '\x00'));
const kp = nacl.sign.keyPair.fromSeed(seed);
const privKey = Buffer.from(kp.secretKey);   // 64 bytes (seed||pub)
const pubKey  = Buffer.from(kp.publicKey);   // 32 bytes

function canonicalMessage(did, nonce) {
  return Buffer.concat([DOMAIN, Buffer.from(did, 'utf8'), Buffer.from([0]), Buffer.from(nonce, 'utf8')]);
}

function signFor(did, nonce) {
  const msg = canonicalMessage(did, nonce);
  return Buffer.from(nacl.sign.detached(msg, privKey));
}

const sigValid       = signFor(WORKER_DID, NONCE);
const sigValidNonce2 = signFor(WORKER_DID, NONCE_OTHER);
const sigWrongDid    = signFor('did:key:z6MkOTHER', NONCE);

// Build a "wrong key" pubkey/sig pair to test rejection
const seed2 = Buffer.from('delibera-test-WRONG-key-seed-77a'.padEnd(32, '\x00'));
const kp2 = nacl.sign.keyPair.fromSeed(seed2);
const sigFromOtherKey = Buffer.from(nacl.sign.detached(canonicalMessage(WORKER_DID, NONCE), Buffer.from(kp2.secretKey)));

console.log(`// Generated by scripts/gen-test-keypair.mjs — do not hand-edit.
// Seed: "delibera-test-controller-seed-42"
// Worker DID: ${WORKER_DID}

pub const TEST_CONTROLLER_PUBKEY_B58: &str = "${bs58.encode(pubKey)}";
pub const TEST_NONCE_1: &str = "${NONCE}";
pub const TEST_NONCE_2: &str = "${NONCE_OTHER}";
pub const TEST_SIG_NONCE_1_B58:        &str = "${bs58.encode(sigValid)}";
pub const TEST_SIG_NONCE_2_B58:        &str = "${bs58.encode(sigValidNonce2)}";
pub const TEST_SIG_WRONG_DID_B58:      &str = "${bs58.encode(sigWrongDid)}";       // signed over a different DID
pub const TEST_SIG_FROM_OTHER_KEY_B58: &str = "${bs58.encode(sigFromOtherKey)}";   // right msg, wrong privkey

// Sanity check: pubkey hex = ${pubKey.toString('hex')}
// canonical message bytes (hex) for (${WORKER_DID}, ${NONCE}):
//   ${canonicalMessage(WORKER_DID, NONCE).toString('hex')}
`);
